#!/usr/bin/env node
// Distils public/catalog/*.json down to the few facts the category copy needs
// (count + a spread of real example subjects) and writes src/data/categoryFacts.json.
//
// Runs BEFORE `vite build` because the React app imports the JSON. Committing
// the output keeps `npm run dev` working without running this first.
import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { displayNames } from '../src/data/puzzleTitles.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CATALOG = path.join(ROOT, 'public', 'catalog')
const OUT = path.join(ROOT, 'src', 'data', 'categoryFacts.mjs')
const SUBJECT_COUNT = 8

/** Pick example subjects that read well in prose: multi-word, short, distinct. */
function pickSubjects(names) {
  const seen = new Set()
  const good = []
  const ok = []
  for (const n of names) {
    const k = n.toLowerCase()
    if (seen.has(k) || n.length > 28 || / by /.test(n) || n.includes('(')) continue
    seen.add(k)
    ;(n.includes(' ') ? good : ok).push(n)
  }
  const pool = good.length >= SUBJECT_COUNT ? good : [...good, ...ok]
  if (pool.length <= SUBJECT_COUNT) return pool
  // Spread the picks across the whole catalogue rather than taking the head.
  const step = pool.length / SUBJECT_COUNT
  return Array.from({ length: SUBJECT_COUNT }, (_, i) => pool[Math.floor(i * step)])
}

const landingKeys = new Set(
  Object.keys(JSON.parse(await fs.readFile(path.join(ROOT, 'src', 'data', 'landings.json'), 'utf8'))),
)
const files = (await fs.readdir(CATALOG)).filter(
  (f) =>
    f.endsWith('.json') &&
    f !== 'index.json' &&
    !f.startsWith('event-') &&
    !f.startsWith('daily') &&
    !f.startsWith('home-') &&
    !landingKeys.has(f.replace(/\.json$/, '')),
)

const categories = {}
let puzzles = 0
for (const file of files.sort()) {
  const key = file.replace(/\.json$/, '')
  const images = JSON.parse(await fs.readFile(path.join(CATALOG, file), 'utf8')).images || []
  if (!images.length) continue
  categories[key] = { count: images.length, subjects: pickSubjects(displayNames(images)) }
  puzzles += images.length
}

const totals = { puzzles, categories: Object.keys(categories).length }
// Emitted as an ES module rather than JSON so that node (the build scripts) and
// Vite (the app) can both import it with no JSON import-attribute support.
await fs.writeFile(
  OUT,
  '// GENERATED by scripts/build-category-facts.mjs - do not edit by hand.\n' +
    `export const TOTALS = ${JSON.stringify(totals)}\n` +
    `export const CATEGORY_FACTS = ${JSON.stringify(categories, null, 2)}\n`,
)
console.log(
  `✓ category facts: ${totals.categories} categories, ${puzzles.toLocaleString()} puzzles → src/data/categoryFacts.mjs`,
)
